#!/usr/bin/env python3
"""Writes offline-assets.js: every file the site needs offline, each with a
short content hash. Run it after changing any file, before committing:

    python3 tools/build-offline-list.py

The service worker (sw.js) and the page use this list to download the site
for offline use; a changed hash makes the iPad download that file again.
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
CORE = ["index.html", "style.css", "script.js", "manifest.webmanifest"]
files = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "assets"], capture_output=True, text=True, check=True).stdout.split()
files = [f for f in files if not f.endswith((".md", ".gitkeep")) and os.path.exists(f)]

def rev(path):
    with open(path, "rb") as fh:
        return hashlib.sha1(fh.read()).hexdigest()[:10]

# Stamp index.html with the current versions of the page code, so a browser
# (or the iPad's saved copy) can never pair a new page with old code.
import re
html = open("index.html", encoding="utf-8").read()
for name in ("style.css", "script.js"):
    html = re.sub(r'(["\'])' + re.escape(name) + r'(\?v=[0-9a-f]*)?(["\'])', r'\g<1>' + name + "?v=" + rev(name) + r'\g<3>', html)
open("index.html", "w", encoding="utf-8").write(html)

assets = [[p, rev(p), os.path.getsize(p)] for p in CORE + sorted(files)]
fonts = ("https://fonts.googleapis.com/css2?family=Cinzel:wght@400;600;700"
         "&family=Heebo:wght@300;400;500;700;800;900&family=Montserrat:wght@300;400;500;600&display=swap")
with open("offline-assets.js", "w") as out:
    out.write("// Generated by tools/build-offline-list.py: do not edit by hand.\n")
    out.write("self.OFFLINE_FONTS_CSS = %s;\n" % json.dumps(fonts))
    out.write("self.OFFLINE_ASSETS = %s;\n" % json.dumps(assets, ensure_ascii=False, indent=0))
print(len(assets), "files,", round(sum(a[2] for a in assets) / 1e6, 1), "MB")
